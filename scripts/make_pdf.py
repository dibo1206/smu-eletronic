def build_pdf():
    OUT_PATH.parent.mkdir(exist_ok=True)
    doc = fitz.open()

    for entry in PAGES:
        title, body = entry[0], entry[1]
        fontsize = entry[2] if len(entry) > 2 else 12

        page = doc.new_page(width=595, height=842)  # A4
        page.insert_font(fontname="malgun", fontfile=str(FONT_PATH))

        page.insert_text((72, 80), title, fontname="malgun", fontsize=16)
        page.draw_line((72, 95), (523, 95), width=1)
        page.insert_textbox(
            fitz.Rect(72, 115, 523, 800),
            body.strip(),
            fontname="malgun",
            fontsize=fontsize,
            lineheight=1.5,
        )

    doc.save(OUT_PATH)
    doc.close()
    print(f"PDF 생성 완료: {OUT_PATH} ({len(PAGES)}페이지)")


if __name__ == "__main__":
    build_pdf()
